#!/usr/bin/env bash

# One canonical monorepo checkout per server. Generated inputs, references,
# logs, agent state and worktrees stay on the data disk outside the checkout.
export AGENTIC3D_DATA_ROOT="${OPENAGENTIC3DBENCH_DEV_ROOT:-/data/gcr}"
export AGENTIC3D_REPO_ROOT="${AGENTIC3D_REPO_ROOT:-$AGENTIC3D_DATA_ROOT/Agentic-Open3DBench}"
export AGENTIC3D_ROOT="$AGENTIC3D_REPO_ROOT/AgenticBench"
export OPEN3DBENCH_ROOT="$AGENTIC3D_REPO_ROOT"
export OPEN3DBENCH_RESULTS_ROOT="${OPEN3DBENCH_RESULTS_ROOT:-$AGENTIC3D_DATA_ROOT/agentic3d-runs}"
export AGENTICBENCH_DATA_ROOT="${AGENTICBENCH_DATA_ROOT:-$OPEN3DBENCH_RESULTS_ROOT}"
export AGENTIC3D_RUNS_ROOT="$OPEN3DBENCH_RESULTS_ROOT/agent-state"
export AGENTIC3D_WORKTREES_ROOT="$OPEN3DBENCH_RESULTS_ROOT/worktrees"
export AGENTIC3D_CACHE_ROOT="${AGENTIC3D_CACHE_ROOT:-$AGENTIC3D_DATA_ROOT/agentic3d-cache}"
export AGENTIC3D_SCOPE_MODE="enforced"
export OPEN3DBENCH_RELEASE_IMAGE="${OPEN3DBENCH_RELEASE_IMAGE:-shiyunqi/open3dbench-v2.0:release}"
export OPEN3DBENCH_PLACE_IMAGE="$OPEN3DBENCH_RELEASE_IMAGE"
export OPEN3DBENCH_EVAL_IMAGE="$OPEN3DBENCH_RELEASE_IMAGE"
export PATH="$HOME/.local/bin:$AGENTIC3D_REPO_ROOT/.venv/bin:$PATH"
export PYTHONPATH="$AGENTIC3D_ROOT${PYTHONPATH:+:$PYTHONPATH}"
